type LanguageListener = (lang: SupportedLanguage) => void;

export class LocalizationService {
  private static currentLang: SupportedLanguage = 'hi';
  private static listeners: Set<LanguageListener> = new Set();

  public static subscribe(listener: LanguageListener): () => void {
    this.listeners.add(listener);
    return () => {
      this.listeners.delete(listener);
    };
  }

  public static setLanguage(lang: SupportedLanguage) {
    this.currentLang = lang;
    try {
      localStorage.setItem('tulsiveda_lang', lang);
      localStorage.setItem('tulsiveda_language', lang);
    } catch {
      // Ignore if localStorage unavailable
    }
    this.listeners.forEach(fn => {
      try { fn(lang); } catch {}
    });
  }

  public static getLanguage(): SupportedLanguage {
    try {
      const saved = (localStorage.getItem('tulsiveda_lang') || localStorage.getItem('tulsiveda_language')) as SupportedLanguage;
      if (saved && TRANSLATIONS[saved]) {
        this.currentLang = saved;
      }
    } catch {
      // Default to Hindi
    }
    return this.currentLang;
  }

  public static getCurrentLanguage(): SupportedLanguage {
    return this.getLanguage();
  }

  public static t(key: string): string {
    const lang = this.getLanguage();

    // 0. Check Extended Translations for exact matches in selected language
    const extTable = EXTENDED_TRANSLATIONS[lang] || EXTENDED_TRANSLATIONS.hi;
    if (extTable && extTable[key]) return extTable[key];

    const table = TRANSLATIONS[lang] || TRANSLATIONS.hi;

    // 1. Exact match
    if (table[key]) return table[key];

    // 2. camelCase to snake_case or vice-versa
    const camelKey = key.replace(/_([a-z])/g, (_, g) => g.toUpperCase());
    if (extTable && extTable[camelKey]) return extTable[camelKey];
    if (table[camelKey]) return table[camelKey];

    const snakeKey = key.replace(/([A-Z])/g, '_$1').toLowerCase();
    if (extTable && extTable[snakeKey]) return extTable[snakeKey];
    if (table[snakeKey]) return table[snakeKey];

    // 3. Fallback to English
    const extEn = EXTENDED_TRANSLATIONS.en || {};
    if (extEn[key]) return extEn[key];
    if (extEn[camelKey]) return extEn[camelKey];
    if (extEn[snakeKey]) return extEn[snakeKey];

    const enTable = TRANSLATIONS.en || {};
    if (enTable[key]) return enTable[key];
    if (enTable[camelKey]) return enTable[camelKey];
    if (enTable[snakeKey]) return enTable[snakeKey];

    // 4. Fallback to Hindi
    const extHi = EXTENDED_TRANSLATIONS.hi || {};
    if (extHi[key]) return extHi[key];
    if (extHi[camelKey]) return extHi[camelKey];
    if (extHi[snakeKey]) return extHi[snakeKey];

    const hiTable = TRANSLATIONS.hi || {};
    if (hiTable[key]) return hiTable[key];
    if (hiTable[camelKey]) return hiTable[camelKey];
    if (hiTable[snakeKey]) return hiTable[snakeKey];

    // 5. Friendly human-readable fallback (never raw underscores)
    return key.replace(/_/g, ' ').replace(/\b\w/g, l => l.toUpperCase());
  }

  public static getBcp47(): string {
    const meta = SUPPORTED_LANGUAGES.find((l) => l.code === this.getLanguage());
    return meta ? meta.bcp47 : 'hi-IN';
  }
}

export function useCurrentLanguage(): SupportedLanguage {
  const [lang, setLang] = useState<SupportedLanguage>(() => LocalizationService.getLanguage());
  useEffect(() => {
    return LocalizationService.subscribe((newLang) => {
      setLang(newLang);
    });
  }, []);
  return lang;
}

export const t = (key: string): string => LocalizationService.t(key);
export const getStoredLanguage = (): SupportedLanguage => LocalizationService.getLanguage();
export const setStoredLanguage = (lang: SupportedLanguage): void => LocalizationService.setLanguage(lang);
