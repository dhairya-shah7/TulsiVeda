export class EmergencyTriageService {
  /**
   * Fast regex-based detection across 12 languages for emergency life-threats
   */
    public static evaluateEmergency(queryText: string): EmergencyCase | null {
    const q = (queryText || '').toLowerCase().trim();
    if (!q) return null;

    // 0. ACUTE STROKE & BRAIN ATTACK EMERGENCY (Highest priority life-threat)
    const strokeRegex = /\b(stroke|brain\s*attack|paralysis|lakwa|falij|pakshaghata|facial\s*droop|slurred\s*speech|hemiplegia|paresis)\b|स्ट्रोक|लकवा|फालिज|पक्षाघात|लकवे|લકવો|ફેસિયલ\s*ડ્રોપ|પક્ષાઘાત|ਸਟ੍ਰੋਕ|ਲਕਵਾ|ಪಾರ್ಶ್ವವಾಯು|ಲಕ್ವ|பக்கவாதம்|பக்கவாதி|పక్షవాతం|స్ట్రోక్|പക്ഷാഘാതം|സ്ട്രോക്ക്|স্ট্রোক|প্যারালাইসিস|পক্ষাঘাত|ପକ୍ଷାଘାତ|ষ্ট্ৰোক/i;
    if (strokeRegex.test(q)) {
      return EMERGENCY_PROTOCOLS.STROKE;
    }

    // 1. CARDIAC EMERGENCY
    const cardiacRegex = /heart\s*attack|cardiac|chest\s*pain|angina|chhati\s*me\s*dard|dil\s*ka\s*daura|हार्ट\s*अटैक|दिल\s*का\s*दौरा|छाती\s*में\s*दर्द|हृदय|હાર્ટ\s*એટેક|છાતીમાં\s*દુખાવો|ਹਾਰਟ\s*ਅਟੈਕ|ਛਾਤੀ\s*ਦਰਦ|மாரடைப்பு|நெஞ்சு\s*வலி|గుండెపోటు|ఛాతీ\s*నొప్పి|ಹೃದಯಾಘಾತ|ಎದೆ\s*ನೋವು|ഹാർട്ട്\s*അറ്റാക്ക്|നെഞ്ചുവേദന|হার্ট\s*অ্যাটাক|বুকে\s*ব্যথা|ହୃଦଘାତ|ছাতি\s*বিষ/i;
    if (cardiacRegex.test(q)) {
      return EMERGENCY_PROTOCOLS.CARDIAC;
    }

    // 2. POISONING OR SNAKEBITE
    const poisonSnakeRegex = /poison|poisoning|snake|saanp|saap|zeher|zahar|bichhu|snake\s*bite|scorpion|pesticide|organophosphate|ज़हर|विषाक्त|सांप|सर्पदंश|बिच्छू|કીટનાશક|ઝેર|સાપ|વીંછી|ਡੰਗ|ਸੱਪ|ਜ਼ਹਿਰ|நஞ்சு|பாம்புக்கடி|విషం|పాముకాటు|విషప్రయోగం|ವಿಷ|ಹಾವಿನ\s*ಕಡಿತ|വിഷബാധ|പാമ്പുകടി|বিষ|সাপের\s*কামড়|ବିଷ|ସାପ\s*କାମୁଡ଼ା|কীটনাশক|সাপে\s*খোৱা/i;
    if (poisonSnakeRegex.test(q)) {
      return EMERGENCY_PROTOCOLS.POISONING_SNAKEBITE;
    }

    // 3. ANAPHYLAXIS & SEVERE AIRWAY OBSTRUCTION
    const anaphylaxisRegex = /anaphylaxis|throat\s*swelling|unable\s*to\s*breathe|gasping|stridor|choking|गला\s*घोंटना|गले\s*में\s*सूजन|सांस\s*रुकना|શ્વાસ\s*રુંધાવો|ગળું\s*સૂજવું|ਸਾਹ\s*ਬੰਦ|மூச்சுத்திணறல்|శ్వాస\s*ఆగడం|ಉಸಿರುಗಟ್ಟುವುದು|ശ്വാസംമുട്ടൽ|দম\s*বন্ধ|ଶ୍ୱାସ\s*ରୁଦ୍ଧ/i;
    if (anaphylaxisRegex.test(q)) {
      return EMERGENCY_PROTOCOLS.ANAPHYLAXIS;
    }

    return null;
  }
}
