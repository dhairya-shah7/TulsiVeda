  /**
   * Get localized condition title for any condition ID
   */
  public static getConditionTitle(id: string, defaultName: string, lang: string): string {
    const l = (lang || 'en').toLowerCase().slice(0, 2);
    if (this.CONDITION_TITLES[id] && this.CONDITION_TITLES[id][l]) {
      return this.CONDITION_TITLES[id][l];
    }
    // If English, return English title
    if (l === 'en') return defaultName;

    // If we have Hindi and target is Indic, provide clean fallback without English
    if (this.CONDITION_TITLES[id] && this.CONDITION_TITLES[id].hi) {
      return this.CONDITION_TITLES[id].hi;
    }

    return defaultName;
  }
